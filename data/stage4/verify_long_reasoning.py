"""Verify generated long reasoning traces with an LLM judge.

Modes:
  oo: previous reasoning is the original short reasoning, `data["response"]`.
  xo: previous reasoning is the incorrect short reasoning, read from
      `<wrong_cot>/{key}.json` (field "wrong_response").
The gold answer is read from the metadata entry itself (`data["answer"]`).
"""

import argparse
import json
import os
from queue import Queue
from threading import Lock, Thread

from openai import OpenAI
from tqdm import tqdm

file_lock = Lock()

DESCRIPTION_NOTE = (
    "Note: The descriptions below are helpful hints, automatically generated by models, and may contain inaccuracies. "
    "Use the parts that seem relevant to the question and choices."
    "If information conflicts, prefer the evidence that is most directly supported by the question/choices and is most consistent with the overall context. "
)

SYSTEM_PROMPT = (
    "You are a verification assistant.\n"
    "Your role is to evaluate the provided continued reasoning according to the given verification criteria and produce a JSON judgment in the specified output format.\n"
    "Follow the instructions precisely.\n"
)


def json_post_process(response: str) -> dict:
    start = response.find("{")
    end = response.rfind("}")

    json_str = response[start : end + 1]

    try:
        return json.loads(json_str)
    except Exception:
        return None


def save_result(key: str, response_json: dict, save_path: str):
    """Thread-safe result saving"""
    with file_lock:
        file_path = os.path.join(save_path, f"{key}.json")
        os.makedirs(os.path.dirname(file_path), exist_ok=True)

        with open(file_path, "w") as f:
            json.dump(response_json, f, indent=2, ensure_ascii=False)


def build_user_prompt(
    data: dict,
    audio_description: str,
    previous_reasoning: str,
    continued_reasoning: str,
    correct_answer: str,
    user_prompt_template: str,
) -> str:

    audio_description = DESCRIPTION_NOTE + "\n\n" + audio_description

    prompt = (
        user_prompt_template.replace("__QUESTION__", data["question"])
        .replace("__AUDIO_DESCRIPTION__", audio_description)
        .replace("__R_PREV__", previous_reasoning)
        .replace("__R_CONT__", continued_reasoning)
        .replace("__CORRECT_ANSWER__", correct_answer)
    )
    return prompt


def worker_fn(
    task_queue: Queue,
    result_queue: Queue,
    progress_bar: tqdm,
    prompt: dict,
    save_path: str,
    args,
):
    """Worker function for verifying continued CoT reasoning"""
    client = OpenAI(
        base_url=args.vllm_base_url,
        api_key="",
    )
    model = args.vllm_model

    while True:
        data = task_queue.get()
        if data is None:  # Termination signal
            task_queue.task_done()
            break

        try:
            (
                key,
                entry,
                audio_description,
                previous_reasoning,
                continued_reasoning,
                correct_answer,
            ) = data
            user_prompt = build_user_prompt(
                entry,
                audio_description,
                previous_reasoning,
                continued_reasoning,
                correct_answer,
                prompt["user"],
            )

            # API call
            completion = client.chat.completions.create(
                model=model,
                messages=[
                    {"role": "system", "content": prompt["system"]},
                    {
                        "role": "user",
                        "content": user_prompt,
                    },
                ],
                temperature=0.7,
                top_p=0.8,
                max_tokens=4096,
                extra_body={"top_k": 20, "min_p": 0},
            )

            message = completion.choices[0].message
            content = message.content if message.content else ""
            if content == "":
                raise ValueError("Model response is empty")

            response_json = json_post_process(content)

            # Save result immediately
            if response_json is not None:
                save_result(key, response_json, save_path)
                result_queue.put((key, None))
            else:
                result_queue.put((key, "JSON parsing error"))

        except Exception as e:
            print(f"Error processing {key}: {str(e)}")
            result_queue.put((key, str(e)))
        finally:
            task_queue.task_done()
            progress_bar.update(1)


def parse_args():
    parser = argparse.ArgumentParser(
        description="Verifying long CoT reasoning from Qwen3 via OpenAI API"
    )
    parser.add_argument(
        "--mode",
        type=str,
        required=True,
        choices=["oo", "xo"],
        help="oo: previous reasoning is the original response; xo: previous reasoning is the wrong CoT",
    )
    parser.add_argument(
        "--input",
        "-i",
        type=str,
        default="../examples/afthink_metadata_sample.json",
        help="Input JSON file containing metadata entries (with question/response/answer).",
    )
    parser.add_argument(
        "--user_prompt",
        "-up",
        type=str,
        default="verify_user_prompt.txt",
        help="File with verification prompt template",
    )
    parser.add_argument(
        "--save_path",
        "-s",
        type=str,
        default=None,
        help="Path to save verification results (default: ../../workdir/cot_verified/{mode})",
    )
    parser.add_argument(
        "--description_path",
        "-d",
        type=str,
        default="../../workdir/descriptions",
        help="Path to audio descriptions",
    )
    parser.add_argument(
        "--long_cot_path",
        "-lc",
        type=str,
        default=None,
        help="Path to long CoT files (default: ../../workdir/long_cot/{mode})",
    )
    parser.add_argument(
        "--wrong_cot",
        "-wc",
        type=str,
        default="../../workdir/wrong_cot",
        help="[xo] Path to wrong CoT files (JSON format with 'wrong_response' field)",
    )
    parser.add_argument(
        "--num_workers",
        "-w",
        type=int,
        default=256,
        help="Number of worker threads",
    )
    parser.add_argument(
        "--vllm_base_url",
        type=str,
        default="http://127.0.0.1:8003/v1",
        help="Base URL for vLLM server",
    )
    parser.add_argument(
        "--vllm_model",
        type=str,
        default="Qwen/Qwen3-Next-80B-A3B-Instruct-FP8",
        help="Model name for vLLM server",
    )
    args = parser.parse_args()
    if args.save_path is None:
        args.save_path = f"../../workdir/cot_verified/{args.mode}"
    if args.long_cot_path is None:
        args.long_cot_path = f"../../workdir/long_cot/{args.mode}"
    return args


def main():
    args = parse_args()

    # Load prompt and input data
    prompt = {
        "user": open(args.user_prompt, "r").read(),
        "system": SYSTEM_PROMPT,
    }
    input_data = json.load(open(args.input, "r"))
    os.makedirs(args.save_path, exist_ok=True)

    print(f"Mode: {args.mode}")
    print(f"Loaded {len(input_data)} entries from {args.input}")

    # Prepare tasks - skip already processed files
    tasks = []
    missing = 0
    processed = 0

    for key, data in tqdm(
        list(input_data.items()), dynamic_ncols=True, desc="Checking existing results"
    ):
        if "original_key" in data:
            description_key = data["original_key"]
        else:
            description_key = key
        description_file = os.path.join(args.description_path, f"{description_key}.txt")
        if not os.path.exists(description_file):
            missing += 1
            continue

        long_cot_file = os.path.join(args.long_cot_path, f"{key}.txt")
        if not os.path.exists(long_cot_file):
            missing += 1
            continue

        if args.mode == "xo":
            wrong_cot_file = os.path.join(args.wrong_cot, f"{key}.json")
            if not os.path.exists(wrong_cot_file):
                missing += 1
                continue

        if "question" not in data or "response" not in data or "answer" not in data:
            missing += 1
            continue

        # Check if result file already exists
        result_file = os.path.join(args.save_path, f"{key}.json")
        if os.path.exists(result_file):
            processed += 1
            continue

        # Load all necessary data
        audio_description = open(description_file, "r").read().strip()

        # Load long CoT (continued reasoning)
        continued_reasoning = open(long_cot_file, "r").read().strip()

        if args.mode == "oo":
            # Previous reasoning is the original response from metadata
            previous_reasoning = data["response"]
        else:
            with open(wrong_cot_file, "r") as f:
                wrong_cot_data = json.load(f)
            if "wrong_response" not in wrong_cot_data:
                print(f"Warning: 'wrong_response' not found in {wrong_cot_file}, skipping.")
                missing += 1
                continue
            previous_reasoning = wrong_cot_data["wrong_response"]

        tasks.append(
            (
                key,
                data,
                audio_description,
                previous_reasoning,
                continued_reasoning,
                data["answer"],
            )
        )

    print(f"Total files: {len(input_data)}")
    print(f"Missing dependencies: {missing}")
    print(f"Already processed: {processed}")
    print(f"To process: {len(tasks)}")

    if len(tasks) == 0:
        print("All files already processed or missing dependencies!")
        return

    # Setup queues and progress bar
    task_queue = Queue(maxsize=args.num_workers * 2)
    result_queue = Queue()
    progress_bar = tqdm(
        total=len(tasks),
        desc=f"Verifying long CoT ({args.mode})",
        dynamic_ncols=True,
    )

    # Start worker threads
    threads = []
    for _ in range(args.num_workers):
        thread = Thread(
            target=worker_fn,
            args=(task_queue, result_queue, progress_bar, prompt, args.save_path, args),
        )
        thread.start()
        threads.append(thread)

    # Add tasks to queue
    for task in tasks:
        task_queue.put(task)

    # Send termination signals
    for _ in range(args.num_workers):
        task_queue.put(None)

    # Wait for completion
    task_queue.join()
    for thread in threads:
        thread.join()

    progress_bar.close()

    # Collect results
    result_cnt = 0
    errors = []

    while not result_queue.empty():
        key, error = result_queue.get()
        if error:
            errors.append(f"{key}: {error}")
        else:
            result_cnt += 1

    # Print summary
    print(f"\nProcessed: {len(tasks)}")
    print(f"Successful: {result_cnt}")
    print(f"Errors: {len(errors)}")
    print(f"Skipped (missing dependencies): {missing}")
    print(f"Skipped (already done): {processed}")
    print(f"Individual files saved to: {args.save_path}")

    if errors:
        error_file = f"verify_{args.mode}_errors.txt"
        with open(error_file, "w") as f:
            f.write("\n".join(errors))
        print(f"Errors saved to {error_file}")


if __name__ == "__main__":
    main()
